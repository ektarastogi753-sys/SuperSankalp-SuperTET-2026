const KEY = "supersankalp_model_paper_04_v1";
const TOTAL = 120;
const DURATION = 120 * 60;
let current = 0;
let answers = Array(TOTAL).fill(null);
let remaining = DURATION;
let finished = false;
let timerId = null;

const $ = id => document.getElementById(id);

function validateQuestions(){
  if(QUESTIONS.length !== TOTAL) {
    alert("प्रश्नों की संख्या 120 नहीं है।");
    return false;
  }
  return QUESTIONS.every(q =>
    q.length === 5 &&
    Array.isArray(q[2]) &&
    q[2].length === 4 &&
    Number.isInteger(q[3]) &&
    q[3] >= 0 && q[3] < 4
  );
}

function save(){
  localStorage.setItem(KEY, JSON.stringify({
    answers, remaining, current
  }));
}

function load(){
  try{
    const data = JSON.parse(localStorage.getItem(KEY));
    if(data && Array.isArray(data.answers) && data.answers.length === TOTAL){
      answers = data.answers;
      remaining = Number.isFinite(data.remaining) ? data.remaining : DURATION;
      current = Math.min(Math.max(data.current || 0,0),TOTAL-1);
    }
  }catch(e){}
}

function render(){
  if(finished) return;
  const q = QUESTIONS[current];
  $("count").textContent = `प्रश्न ${current+1} / ${TOTAL}`;
  $("subject").textContent = q[0];
  $("question").textContent = q[1];
  $("bar").style.width = ((current+1)/TOTAL*100)+"%";

  $("options").innerHTML = "";
  q[2].forEach((op,i)=>{
    const label = document.createElement("label");
    label.className = "option"+(answers[current]===i?" selected":"");
    const input = document.createElement("input");
    input.type = "radio";
    input.name = "answer";
    input.checked = answers[current]===i;
    input.addEventListener("change",()=>{
      answers[current]=i;
      save();
      render();
    });
    label.appendChild(input);
    label.appendChild(document.createTextNode(String.fromCharCode(65+i)+". "+op));
    $("options").appendChild(label);
  });
  renderNumbers();
}

function renderNumbers(){
  $("numbers").innerHTML="";
  QUESTIONS.forEach((q,i)=>{
    const b=document.createElement("div");
    b.className="num"+(answers[i]!==null?" done":"")+(i===current?" current":"");
    b.textContent=i+1;
    b.onclick=()=>{current=i;save();render();};
    $("numbers").appendChild(b);
  });
}

function next(){
  if(current<TOTAL-1){current++;save();render();}
}
function previous(){
  if(current>0){current--;save();render();}
}
function clearAnswer(){
  answers[current]=null;save();render();
}

function formatTime(sec){
  const m=Math.floor(sec/60);
  const s=sec%60;
  return String(m).padStart(2,"0")+":"+String(s).padStart(2,"0");
}

function startTimer(){
  $("timer").textContent=formatTime(remaining);
  timerId=setInterval(()=>{
    if(finished)return;
    remaining--;
    $("timer").textContent=formatTime(remaining);
    if(remaining<=0){
      clearInterval(timerId);
      submitTest(true);
    }else if(remaining%5===0){
      save();
    }
  },1000);
 }
function submitTest(auto=false){
  if(finished)return;
  if(!auto){
    const unanswered=answers.filter(a=>a===null).length;
    if(!confirm(`आपके ${unanswered} प्रश्न अनुत्तरित हैं। क्या टेस्ट जमा करना चाहते हैं?`))return;
  }
  finished=true;
  clearInterval(timerId);
  save();

  let correct=0,wrong=0,blank=0;
  QUESTIONS.forEach((q,i)=>{
    if(answers[i]===null)blank++;
    else if(answers[i]===q[3])correct++;
    else wrong++;
  });

  const score=correct*3-wrong;
  $("test").style.display="none";
  $("submitBox").style.display="none";
  $("result").style.display="block";
  $("score").innerHTML=`
    <h3>प्राप्तांक: ${score} / 360</h3>
    <p class="correct">सही उत्तर: ${correct}</p>
    <p class="wrong">गलत उत्तर: ${wrong}</p>
    <p>अनुत्तरित: ${blank}</p>
    <p>सही प्रतिशत: ${(correct/TOTAL*100).toFixed(2)}%</p>
  `;

  $("review").innerHTML="<h3>उत्तर एवं व्याख्या</h3>";
  QUESTIONS.forEach((q,i)=>{
    const ok=answers[i]===q[3];
    const status=answers[i]===null?"अनुत्तरित":ok?"सही":"गलत";
    const div=document.createElement("div");
    div.className="explain";
    const title=document.createElement("b");
    title.textContent=`${i+1}. ${q[1]}`;
    const st=document.createElement("p");
    st.className=ok?"correct":answers[i]===null?"":"wrong";
    st.textContent="आपका उत्तर: "+(answers[i]===null?"नहीं दिया":q[2][answers[i]])+" | "+status;
    const ans=document.createElement("p");
    ans.innerHTML="<b>सही उत्तर: </b>";
    ans.appendChild(document.createTextNode(q[2][q[3]]));
    const exp=document.createElement("p");
    exp.textContent="व्याख्या: "+q[4];
    div.append(title,st,ans,exp);
    $("review").appendChild(div);
  });
  window.scrollTo(0,0);
}

function resetTest(){
  if(!confirm("क्या आप टेस्ट के सभी उत्तर मिटाकर दोबारा शुरू करना चाहते हैं?"))return;
  localStorage.removeItem(KEY);
  location.reload();
}

load();
if(validateQuestions()){
  render();
  startTimer();
}
