/* ================= ENGINE ================= */

const TOTAL = QUESTIONS.length;
const DURATION = 120 * 60;
const STORE = "supersankalp_model_paper_01";
const RESULT_STORE = "supersankalp_model_paper_01_result";

let answers = {};
let marked = [];
let current = 0;
let remaining = DURATION;
let timer = null;
let submitted = false;
let finalResult = null;

const $ = id => document.getElementById(id);

function saveAttempt() {
  if (submitted) return;
  try {
    localStorage.setItem(STORE, JSON.stringify({
      answers, marked, current, remaining,
      started: true
    }));
  } catch(e) {
    console.warn("Save error", e);
  }
}

function loadAttempt() {
  try {
    const data = JSON.parse(localStorage.getItem(STORE) || "null");
    if (!data || !data.started) return false;
    answers = data.answers || {};
    marked = data.marked || [];
    current = Math.min(Math.max(0, data.current || 0), TOTAL - 1);
    remaining = Number.isFinite(data.remaining)
      ? Math.max(0, data.remaining) : DURATION;
    return true;
  } catch(e) {
    return false;
  }
}

function showIntro() {
  $("intro").classList.remove("hidden");
  $("exam").classList.add("hidden");
  $("result").classList.add("hidden");
}

function showExam() {
  $("intro").classList.add("hidden");
  $("exam").classList.remove("hidden");
  $("result").classList.add("hidden");
  renderQuestion();
  renderPalette();
  updateStats();
  startTimer();
}

function startNewExam() {
  if (localStorage.getItem(STORE) &&
      !confirm("नई परीक्षा शुरू करने पर पुरानी अधूरी परीक्षा हट जाएगी। जारी रखें?")) return;

  answers = {};
  marked = [];
  current = 0;
  remaining = DURATION;
  submitted = false;
  finalResult = null;
  localStorage.removeItem(RESULT_STORE);
  saveAttempt();
  showExam();
}

function startTimer() {
  clearInterval(timer);
  updateTimer();
  timer = setInterval(() => {
    remaining--;
    updateTimer();
    if (remaining % 5 === 0) saveAttempt();
    if (remaining <= 0) {
      remaining = 0;
      clearInterval(timer);
      submitExam(true);
    }
  }, 1000);
}

function updateTimer() {
  const h = Math.floor(remaining / 3600);
  const m = Math.floor((remaining % 3600) / 60);
  const s = remaining % 60;
  $("timer").textContent =
    [h,m,s].map(n => String(n).padStart(2,"0")).join(":");
  $("timer").style.color = remaining < 300 ? "#b42318" : "#16794b";
}

function renderQuestion() {
  const q = QUESTIONS[current];
  $("qNo").textContent = (current + 1) + "/" + TOTAL;
  $("subjectName").textContent = q[0].includes("संविधान") ? "सामान्य ज्ञान" : "प्रश्न " + (current + 1);
  $("question").textContent = (current + 1) + ". " + q[0];

  const box = $("options");
  box.innerHTML = "";
  q[1].forEach((option, i) => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "option" + (answers[current] === i ? " selected" : "");
    btn.textContent = String.fromCharCode(65 + i) + ". " + option;
    btn.addEventListener("click", () => {
      answers[current] = i;
      saveAttempt();
      renderQuestion();
      renderPalette();
      updateStats();
    });
    box.appendChild(btn);
  });

  $("prevBtn").disabled = current === 0;
  $("nextBtn").disabled = current === TOTAL - 1;
  $("markBtn").textContent = marked.includes(current)
    ? "★ समीक्षा हटाएँ" : "★ समीक्षा हेतु रखें";
}
function renderPalette() {
  const box = $("palette");
  box.innerHTML = "";
  QUESTIONS.forEach((q, i) => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.textContent = i + 1;
    if (answers[i] !== undefined) btn.classList.add("done");
    if (marked.includes(i)) btn.classList.add("review");
    if (i === current) btn.classList.add("current");
    btn.addEventListener("click", () => {
      current = i;
      saveAttempt();
      renderQuestion();
      renderPalette();
    });
    box.appendChild(btn);
  });
}

function updateStats() {
  $("attempted").textContent = Object.keys(answers).length;
  $("marked").textContent = marked.length;
}

function calculateResult() {
  let right = 0, wrong = 0, unattempted = 0;
  QUESTIONS.forEach((q, i) => {
    if (answers[i] === undefined) unattempted++;
    else if (answers[i] === q[2]) right++;
    else wrong++;
  });
  return {
    right, wrong, unattempted,
    score: right * 3 - wrong,
    percentage: ((right * 3 - wrong) / 360 * 100).toFixed(2)
  };
}

function submitExam(auto = false) {
  if (submitted) return;
  if (!auto && !confirm("क्या आप परीक्षा सबमिट करना चाहते हैं? इसके बाद उत्तर नहीं बदल सकेंगे।")) return;
  submitted = true;
  clearInterval(timer);
  const r = calculateResult();
  finalResult = {
    ...r, answers, marked,
    date: new Date().toLocaleString("hi-IN")
  };

  localStorage.setItem(RESULT_STORE, JSON.stringify(finalResult));
  localStorage.removeItem(STORE);
  showResult(finalResult);
}

function showResult(r) {
  $("intro").classList.add("hidden");
  $("exam").classList.add("hidden");
  $("result").classList.remove("hidden");

  $("score").textContent = r.score;
  $("right").textContent = r.right;
  $("wrong").textContent = r.wrong;
  $("resultSummary").textContent =
    "कुल अंक: 360 | प्रतिशत: " + r.percentage +
    "% | " + (r.date || "");
  $("unattempted").textContent =
    "बिना उत्तर: " + r.unattempted +
    " | सही: " + r.right + " | गलत: " + r.wrong;

  const wrongBox = $("wrongReview");
  const fullBox = $("fullReview");
  wrongBox.innerHTML = "";
  fullBox.innerHTML = "";

  QUESTIONS.forEach((q, i) => {
    const selected = r.answers[i];
    const correct = q[2];
    const isWrong = selected !== undefined && selected !== correct;

    const html = document.createElement("div");
    html.className = "review-item";

    let selectedText = selected === undefined
      ? "उत्तर नहीं दिया"
      : String.fromCharCode(65 + selected) + ". " + q[1][selected];

    html.innerHTML =
      "<strong>प्रश्न " + (i + 1) + ".</strong> " + q[0] +
      "<br>आपका उत्तर: " +
      (isWrong ? '<span class="wrong-text">' + selectedText + '</span>' : selectedText) +
      "<br>सही उत्तर: <span class='correct-text'>" +
      String.fromCharCode(65 + correct) + ". " + q[1][correct] +
      "</span><br><span class='small'>व्याख्या: " + q[3] + "</span>";

    fullBox.appendChild(html.cloneNode(true));
    if (isWrong) wrongBox.appendChild(html);
  });

  if (!wrongBox.children.length) {
    wrongBox.textContent = "बहुत अच्छा! आपने कोई गलत उत्तर नहीं दिया।";
  }

  $("saveResultBtn").textContent = "परिणाम सुरक्षित है ✓";
}

function showSavedResult() {
  try {
    const r = JSON.parse(localStorage.getItem(RESULT_STORE) || "null");
    if (!r) return;
    submitted = true;
    showResult(r);
  } catch(e) {
    alert("सुरक्षित परिणाम पढ़ने में समस्या हुई।");
  }
}

function resetPaper() {
  if (!confirm("क्या आप इस मॉडल पेपर का पूरा सुरक्षित रिकॉर्ड मिटाकर रीसेट करना चाहते हैं?")) return;
  clearInterval(timer);
  localStorage.removeItem(STORE);
  localStorage.removeItem(RESULT_STORE);
  answers = {};
  marked = [];
  current = 0;
  remaining = DURATION;
  submitted = false;
  finalResult = null;
  showIntro();
  updateHomeButtons();
}

function updateHomeButtons() {
  const hasAttempt = !!localStorage.getItem(STORE);
  const hasResult = !!localStorage.getItem(RESULT_STORE);
  $("resumeBtn").classList.toggle("hidden", !hasAttempt);
  $("savedResultBtn").classList.toggle("hidden", !hasResult);
  $("startBtn").textContent = hasAttempt
    ? "नई परीक्षा शुरू करें" : "परीक्षा शुरू करें";
}

/* ================= EVENTS ================= */

$("startBtn").addEventListener("click", startNewExam);

$("resumeBtn").addEventListener("click", () => {
  if (loadAttempt()) showExam();
  else alert("कोई अधूरी परीक्षा नहीं मिली।");
});

$("savedResultBtn").addEventListener("click", showSavedResult);

$("prevBtn").addEventListener("click", () => {
  if (current > 0) {
    current--;
    saveAttempt();
    renderQuestion();
    renderPalette();
  }
});

$("nextBtn").addEventListener("click", () => {
  if (current < TOTAL - 1) {
    current++;
    saveAttempt();
    renderQuestion();
    renderPalette();
  }
});

$("markBtn").addEventListener("click", () => {
  if (marked.includes(current)) {
    marked = marked.filter(x => x !== current);
  } else {
    marked.push(current);
  }
  saveAttempt();
  renderQuestion();
  renderPalette();
  updateStats();
});

$("clearBtn").addEventListener("click", () => {
  delete answers[current];
  saveAttempt();
  renderQuestion();
  renderPalette();
  updateStats();
});

$("submitBtn").addEventListener("click", () => submitExam(false));

$("saveResultBtn").addEventListener("click", () => {
  if (finalResult) {
    localStorage.setItem(RESULT_STORE, JSON.stringify(finalResult));
    alert("आपका परिणाम इसी ब्राउज़र में सुरक्षित है।");
  } else {
    alert("परिणाम पहले से सुरक्षित है।");
  }
});

$("resetBtn").addEventListener("click", resetPaper);

$("homeBtn").addEventListener("click", () => {
  window.location.href = "./index.html";
});

/* ================= INITIALIZATION ================= */

if (QUESTIONS.length !== 120) {
  alert("प्रश्न बैंक में त्रुटि: कुल प्रश्न 120 नहीं हैं।");
}

updateHomeButtons();

if (localStorage.getItem(RESULT_STORE)) {
  $("savedResultBtn").classList.remove("hidden");
}

if (localStorage.getItem(STORE)) {
  $("resumeBtn").classList.remove("hidden");
}
