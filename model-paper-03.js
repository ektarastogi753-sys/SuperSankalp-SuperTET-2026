/* ===== परीक्षा संचालन प्रणाली ===== */

const TOTAL = 120;
const DURATION = 120 * 60;
const STORE = "supersankalp_model_paper_03_v1";

let answers = {};
let marked = [];
let current = 0;
let remaining = DURATION;
let timer = null;
let submitted = false;
let resultData = null;

const $ = id => document.getElementById(id);

function saveState(){
  localStorage.setItem(STORE, JSON.stringify({
    answers, marked, current, remaining, submitted, resultData
  }));
}

function loadState(){
  try{
    return JSON.parse(localStorage.getItem(STORE) || "null");
  }catch(e){return null;}
}

function showIntro(){
  $("intro").classList.remove("hidden");
  $("exam").classList.add("hidden");
  $("result").classList.add("hidden");
}

function showExam(){
  $("intro").classList.add("hidden");
  $("exam").classList.remove("hidden");
  $("result").classList.add("hidden");
  renderQuestion();
  startTimer();
}

function startTimer(){
  clearInterval(timer);
  updateTimer();
  timer = setInterval(()=>{
    if(remaining > 0){
      remaining--;
      updateTimer();
      if(remaining % 5 === 0) saveState();
    }else{
      clearInterval(timer);
      submitExam(true);
    }
  },1000);
}

function updateTimer(){
  const h = Math.floor(remaining/3600);
  const m = Math.floor((remaining%3600)/60);
  const s = remaining%60;
  $("timer").textContent =
    [h,m,s].map(v=>String(v).padStart(2,"0")).join(":");
}

function renderQuestion(){
  const q = QUESTIONS[current];
  $("qNo").textContent = (current+1)+"/"+TOTAL;
  $("subjectName").textContent = "प्रश्न "+(current+1)+" • "+q[0];
  $("question").textContent = q[1];
  $("options").innerHTML = "";

  q[2].forEach((option,i)=>{
    const btn = document.createElement("button");
    btn.className = "option" + (answers[current]===i ? " selected" : "");
    btn.textContent = String.fromCharCode(65+i)+". "+option;
    btn.onclick = ()=>{
      if(submitted) return;
      answers[current] = i;
      saveState();
      renderQuestion();
    };
    $("options").appendChild(btn);
  });

  $("prevBtn").disabled = current===0;
  $("nextBtn").disabled = current===TOTAL-1;
  $("markBtn").textContent = marked.includes(current)
    ? "★ समीक्षा से हटाएँ" : "★ समीक्षा हेतु रखें";

  updateStats();
  renderPalette();
}

function updateStats(){
  $("attempted").textContent = Object.keys(answers).length;
  $("marked").textContent = marked.length;
}

function renderPalette(){
  $("palette").innerHTML = "";
  for(let i=0;i<TOTAL;i++){
    const b = document.createElement("button");
    b.textContent = i+1;
    if(answers[i]!==undefined) b.classList.add("done");
    if(marked.includes(i)) b.classList.add("review");
    if(i===current) b.classList.add("current");
    b.onclick = ()=>{
      current=i;
      saveState();
      renderQuestion();
    };
    $("palette").appendChild(b);
  }
}

function calculate(){
  let right=0, wrong=0, blank=0;
  QUESTIONS.forEach((q,i)=>{
    if(answers[i]===undefined) blank++;
    else if(answers[i]===q[3]) right++;
    else wrong++;
  });
  return {
    right, wrong, blank,
    score:right*3-wrong,
    percentage:((right*3-wrong)/360*100).toFixed(2)
  };
}

function submitExam(auto=false){
  if(submitted) return;
  if(!auto && !confirm("क्या आप परीक्षा सबमिट करना चाहते हैं? सबमिट करने के बाद उत्तर नहीं बदल पाएँगे।")) return;

  clearInterval(timer);
  submitted=true;
  resultData=calculate();
  saveState();
  showResult();
}

function showResult(){
  $("intro").classList.add("hidden");
  $("exam").classList.add("hidden");
  $("result").classList.remove("hidden");

  const r=resultData || calculate();
  $("score").textContent=r.score;
  $("right").textContent=r.right;
  $("wrong").textContent=r.wrong;
  $("resultSummary").textContent=
    "आपका प्रतिशत: "+r.percentage+"% | सही उत्तर: "+r.right+
    " | गलत उत्तर: "+r.wrong;
  $("unattempted").textContent="बिना उत्तर छोड़े गए प्रश्न: "+r.blank;

  let wrongHTML="";
  let fullHTML="";

  QUESTIONS.forEach((q,i)=>{
    const selected=answers[i];
    const isRight=selected===q[3];
    const correctText=String.fromCharCode(65+q[3])+". "+q[2][q[3]];
    const selectedText=selected===undefined
      ? "उत्तर नहीं दिया"
      : String.fromCharCode(65+selected)+". "+q[2][selected];

    const explanation=
      '<div class="review-item"><b>प्रश्न '+(i+1)+':</b> '+q[1]+
      '<br><span class="correct-text">सही उत्तर: '+correctText+'</span>'+
      '<br>आपका उत्तर: '+selectedText+
      '<br><b>व्याख्या:</b> '+q[4]+'</div>';

    fullHTML+=explanation;
    if(selected!==undefined && !isRight) wrongHTML+=explanation;
  });

  $("wrongReview").innerHTML=wrongHTML ||
    '<p class="correct-text">बहुत अच्छा! कोई गलत उत्तर नहीं है।</p>';
  $("fullReview").innerHTML=fullHTML;
  saveState();
}

$("startBtn").onclick=()=>{
  if(!confirm("परीक्षा शुरू करें? समय 120 मिनट होगा।")) return;
  answers={}; marked=[]; current=0;
  remaining=DURATION; submitted=false; resultData=null;
  saveState();
  showExam();
};

$("resumeBtn").onclick=()=>{
  const d=loadState();
  if(!d) return;
  answers=d.answers||{};
  marked=d.marked||[];
  current=d.current||0;
  remaining=Number.isFinite(d.remaining)?d.remaining:DURATION;
  submitted=!!d.submitted;
  resultData=d.resultData||null;
  if(submitted) showResult();
  else showExam();
};

$("savedResultBtn").onclick=()=>{
  const d=loadState();
  if(!d || !d.submitted) return;
  answers=d.answers||{};
  resultData=d.resultData||calculate();
  submitted=true;
  showResult();
};

$("prevBtn").onclick=()=>{
  if(current>0){current--;saveState();renderQuestion();}
};
$("nextBtn").onclick=()=>{
  if(current<TOTAL-1){current++;saveState();renderQuestion();}
};
$("clearBtn").onclick=()=>{
  delete answers[current];
  saveState();
  renderQuestion();
};
$("markBtn").onclick=()=>{
  if(marked.includes(current))
    marked=marked.filter(x=>x!==current);
  else marked.push(current);
  saveState();
  renderQuestion();
};
$("submitBtn").onclick=()=>submitExam(false);
$("saveResultBtn").onclick=()=>{
  saveState();
  alert("आपका परिणाम इस ब्राउज़र में सुरक्षित कर दिया गया है।");
};
$("resetBtn").onclick=()=>{
  if(!confirm("क्या आप इस पेपर का पूरा प्रयास और परिणाम मिटाकर रीसेट करना चाहते हैं?"))
    return;
  clearInterval(timer);
  localStorage.removeItem(STORE);
  answers={}; marked=[]; current=0;
  remaining=DURATION; submitted=false; resultData=null;
  $("resumeBtn").classList.add("hidden");
  $("savedResultBtn").classList.add("hidden");
  showIntro();
};
$("homeBtn").onclick=()=>window.location.href="./index.html";

/* प्रश्नों की संख्या जाँच */
if(QUESTIONS.length!==TOTAL){
  document.body.innerHTML=
    "<h2 style='padding:20px;color:red'>त्रुटि: प्रश्नों की संख्या "+QUESTIONS.length+
    " है, जबकि 120 होनी चाहिए।</h2>";
}else{
  const saved=loadState();
  if(saved){
    if(saved.submitted){
      $("savedResultBtn").classList.remove("hidden");
    }else{
      $("resumeBtn").classList.remove("hidden");
    }
  }
}
