/* ================= CONFIGURATION ================= */

const TOTAL = QUESTIONS.length;
const DURATION = 120 * 60;

const STORE = "SUPERSANKALP_MODEL02_ATTEMPT";
const RESULT_STORE = "SUPERSANKALP_MODEL02_RESULT";

let answers = {};
let marked = [];
let current = 0;
let remaining = DURATION;
let submitted = false;
let finalResult = null;
let timer = null;

const $ = id => document.getElementById(id);


/* ================= STORAGE ================= */

function saveAttempt() {
  if (submitted) return;

  const data = {
    answers,
    marked,
    current,
    remaining,
    savedAt: Date.now()
  };

  localStorage.setItem(STORE, JSON.stringify(data));
}

function loadAttempt() {
  try {
    const data = JSON.parse(localStorage.getItem(STORE) || "null");

    if (!data) return false;

    answers = data.answers || {};
    marked = data.marked || [];
    current = Math.min(data.current || 0, TOTAL - 1);
    remaining = Math.max(0, data.remaining ?? DURATION);

    return true;
  } catch (e) {
    return false;
  }
}


/* ================= SCREEN CONTROL ================= */

function showIntro() {
  $("intro").classList.remove("hidden");
  $("exam").classList.add("hidden");
  $("result").classList.add("hidden");
}

function showExam() {
  $("intro").classList.add("hidden");
  $("exam").classList.remove("hidden");
  $("result").classList.add("hidden");
  renderQuestion();
  renderPalette();
  updateStats();
  updateTimer();

  clearInterval(timer);

  timer = setInterval(() => {
    remaining--;
    updateTimer();

    if (remaining <= 0) {
      submitExam(true);
    } else if (remaining % 5 === 0) {
      saveAttempt();
    }
  }, 1000);
}

function updateTimer() {
  const h = Math.floor(remaining / 3600);
  const m = Math.floor((remaining % 3600) / 60);
  const s = remaining % 60;

  $("timer").textContent =
    String(h).padStart(2, "0") + ":" +
    String(m).padStart(2, "0") + ":" +
    String(s).padStart(2, "0");
}


/* ================= QUESTION DISPLAY ================= */

function renderQuestion() {
  const q = QUESTIONS[current];

  $("qNo").textContent = (current + 1) + "/" + TOTAL;
  $("question").textContent = q[0];

  $("subjectName").textContent =
    "प्रश्न " + (current + 1) + " | मॉडल पेपर 02";

  $("options").innerHTML = "";

  q[1].forEach((option, index) => {
    const btn = document.createElement("button");

    btn.className = "option";

    if (answers[current] === index) {
      btn.classList.add("selected");
    }

    btn.textContent =
      String.fromCharCode(65 + index) + ". " + option;

    btn.addEventListener("click", () => {
      answers[current] = index;
      saveAttempt();
      renderQuestion();
      renderPalette();
      updateStats();
    });

    $("options").appendChild(btn);
  });

  $("prevBtn").disabled = current === 0;
  $("nextBtn").disabled = current === TOTAL - 1;

  $("markBtn").textContent =
    marked.includes(current)
      ? "★ समीक्षा से हटाएँ"
      : "★ समीक्षा हेतु रखें";
}


/* ================= QUESTION PALETTE ================= */

function renderPalette() {
  const box = $("palette");
  box.innerHTML = "";

  QUESTIONS.forEach((q, i) => {
    const btn = document.createElement("button");

    btn.textContent = i + 1;

    if (answers[i] !== undefined) {
      btn.classList.add("done");
    }

    if (marked.includes(i)) {
      btn.classList.add("review");
    }

    if (i === current) {
      btn.classList.add("current");
    }

    btn.addEventListener("click", () => {
      current = i;
      saveAttempt();
      renderQuestion();
      renderPalette();
    });

    box.appendChild(btn);
  });
}

function updateStats() {
  $("attempted").textContent = Object.keys(answers).length;
  $("marked").textContent = marked.length;
}


/* ================= RESULT ================= */

function calculateResult() {
  let right = 0;
  let wrong = 0;
  let unattempted = 0;

  QUESTIONS.forEach((q, i) => {
    if (answers[i] === undefined) {
      unattempted++;
    } else if (answers[i] === q[2]) {
      right++;
    } else {
      wrong++;
    }
  });

  const score = right * 3 - wrong;

  return {
    right,
    wrong,
    unattempted,
    score,
    percentage: (score / 360 * 100).toFixed(2)
  };
}

function submitExam(auto = false) {
  if (submitted) return;

  if (
    !auto &&
    !confirm("क्या आप परीक्षा सबमिट करना चाहते हैं? इसके बाद उत्तर नहीं बदल सकेंगे।")
  ) return;

  submitted = true;

  clearInterval(timer);

  const r = calculateResult();

  finalResult = {
    ...r,
    answers: { ...answers },
    marked: [...marked],
    date: new Date().toLocaleString("hi-IN")
  };

  localStorage.setItem(RESULT_STORE, JSON.stringify(finalResult));
  localStorage.removeItem(STORE);

  showResult(finalResult);
}


/* ================= RESULT REVIEW ================= */
function showResult(r) {
  $("intro").classList.add("hidden");
  $("exam").classList.add("hidden");
  $("result").classList.remove("hidden");

  $("score").textContent = r.score;
  $("right").textContent = r.right;
  $("wrong").textContent = r.wrong;

  $("resultSummary").textContent =
    "कुल अंक: 360 | प्रतिशत: " +
    r.percentage + "% | " + (r.date || "");

  $("unattempted").textContent =
    "बिना उत्तर: " + r.unattempted +
    " | सही: " + r.right +
    " | गलत: " + r.wrong;

  const wrongBox = $("wrongReview");
  const fullBox = $("fullReview");

  wrongBox.innerHTML = "";
  fullBox.innerHTML = "";

  QUESTIONS.forEach((q, i) => {
    const selected = r.answers[i];
    const correct = q[2];

    const isWrong =
      selected !== undefined && selected !== correct;

    const item = document.createElement("div");
    item.className = "review-item";

    const title = document.createElement("strong");
    title.textContent = "प्रश्न " + (i + 1) + ". " + q[0];

    const yourAnswer = document.createElement("div");

    yourAnswer.textContent =
      "आपका उत्तर: " +
      (selected === undefined
        ? "उत्तर नहीं दिया"
        : String.fromCharCode(65 + selected) + ". " + q[1][selected]);

    yourAnswer.className =
      isWrong ? "wrong-text" : "correct-text";

    const correctAnswer = document.createElement("div");
    correctAnswer.className = "correct-text";

    correctAnswer.textContent =
      "सही उत्तर: " +
      String.fromCharCode(65 + correct) + ". " + q[1][correct];

    const explanation = document.createElement("div");
    explanation.className = "small";
    explanation.textContent = "व्याख्या: " + q[3];

    item.appendChild(title);
    item.appendChild(yourAnswer);
    item.appendChild(correctAnswer);
    item.appendChild(explanation);

    fullBox.appendChild(item.cloneNode(true));

    if (isWrong) {
      wrongBox.appendChild(item);
    }
  });

  if (!wrongBox.children.length) {
    wrongBox.textContent =
      "बहुत अच्छा! आपने कोई गलत उत्तर नहीं दिया।";
  }

  $("saveResultBtn").textContent = "परिणाम सुरक्षित है ✓";
}

function showSavedResult() {
  try {
    const r = JSON.parse(
      localStorage.getItem(RESULT_STORE) || "null"
    );

    if (!r) return;

    submitted = true;
    finalResult = r;

    showResult(r);
  } catch (e) {
    alert("सुरक्षित परिणाम पढ़ने में समस्या हुई।");
  }
}


/* ================= RESET ================= */
function resetPaper() {
  if (
    !confirm(
      "क्या आप मॉडल पेपर 02 का पूरा सुरक्षित रिकॉर्ड मिटाकर रीसेट करना चाहते हैं?"
    )
  ) return;

  clearInterval(timer);

  localStorage.removeItem(STORE);
  localStorage.removeItem(RESULT_STORE);

  answers = {};
  marked = [];
  current = 0;
  remaining = DURATION;
  submitted = false;
  finalResult = null;

  showIntro();
  updateHomeButtons();
}


/* ================= HOME BUTTONS ================= */

function updateHomeButtons() {
  const hasAttempt = !!localStorage.getItem(STORE);
  const hasResult = !!localStorage.getItem(RESULT_STORE);

  $("resumeBtn").classList.toggle("hidden", !hasAttempt);
  $("savedResultBtn").classList.toggle("hidden", !hasResult);

  $("startBtn").textContent =
    hasAttempt ? "नई परीक्षा शुरू करें" : "परीक्षा शुरू करें";
}


/* ================= EVENTS ================= */

$("startBtn").addEventListener("click", () => {
  if (localStorage.getItem(STORE)) {
    if (!confirm("पुरानी अधूरी परीक्षा हटाकर नई परीक्षा शुरू करें?")) {
      return;
    }
    localStorage.removeItem(STORE);
  }

  answers = {};
  marked = [];
  current = 0;
  remaining = DURATION;
  submitted = false;

  showExam();
  saveAttempt();
});

$("resumeBtn").addEventListener("click", () => {
  if (loadAttempt()) {
    showExam();
  } else {
    alert("कोई अधूरी परीक्षा नहीं मिली।");
  }
});

$("savedResultBtn").addEventListener("click", showSavedResult);

$("prevBtn").addEventListener("click", () => {
  if (current > 0) {
    current--;
    saveAttempt();
    renderQuestion();
    renderPalette();
  }
});

$("nextBtn").addEventListener("click", () => {
  if (current < TOTAL - 1) {
    current++;
    saveAttempt();
    renderQuestion();
    renderPalette();
  }
});

$("markBtn").addEventListener("click", () => {
  if (marked.includes(current)) {
    marked = marked.filter(x => x !== current);
  } else {
    marked.push(current);
  }

  saveAttempt();
  renderQuestion();
  renderPalette();
  updateStats();
});

$("clearBtn").addEventListener("click", () => {
  delete answers[current];

  saveAttempt();
  renderQuestion();
  renderPalette();
  updateStats();
});

$("submitBtn").addEventListener("click", () => {
  submitExam(false);
});

$("saveResultBtn").addEventListener("click", () => {
  if (finalResult) {
    localStorage.setItem(
      RESULT_STORE,
      JSON.stringify(finalResult)
    );

    alert("मॉडल पेपर 02 का परिणाम सुरक्षित है।");
  }
});

$("resetBtn").addEventListener("click", resetPaper);

$("homeBtn").addEventListener("click", () => {
  window.location.href = "./index.html";
});


